async function readMessages(locale) {
  const file = path.join(localesDir, locale, "messages.json");
  return JSON.parse(await fs.readFile(file, "utf8"));
}

async function writeMessages(locale, rawMessages) {
  const output = {};
  for (const key of Object.keys(base)) {
    output[key] = { message: rawMessages[key] };
  }

  await fs.mkdir(path.join(localesDir, locale), { recursive: true });
  await fs.writeFile(
    path.join(localesDir, locale, "messages.json"),
    `${JSON.stringify(output, null, 2)}\n`
  );
}

function assertComplete(locale, messages) {
  const missing = Object.keys(base).filter((key) => !messages[key]);
  if (missing.length > 0) {
    throw new Error(`${locale} is missing translations: ${missing.join(", ")}`);
  }
}
